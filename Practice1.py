#2.Area of Rectangle
#Question: Calculate the area of a rectangle. - Formula: Area = length × breadth - Input: - Length = 6 - Breadth = 4 - Output: - Area of rectangle is: 24
length = 6
breadth = 4
area = length * breadth
print("Area of rectangle is: " + str(area))

#3.Area of Triangle
#Question: Calculate the area of a triangle using base and height. - 
#Formula: Area = (1/2) × base × height - Input: - Base = 8 - Height = 5 - Output: - Area of triangle is: 20.0
base = 8
height = 5
area = 1/2 * base * height
print("Area of Triangle " + str(area))

