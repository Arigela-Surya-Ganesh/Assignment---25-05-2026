#5.Perimeter of Rectangle
#Question: Calculate the perimeter of a rectangle. - 
#Formula: Perimeter = 2 × (length + breadth) - Input: - Length = 5 - Breadth = 3 - Output: - Perimeter of rectangle is: 16
